// Resuelve cada vacante con su stack (technologies) usando el puente vacante↔tecnología.
export function getMockVacanciesWithStack(): VacancyWithStack[] {
  const byVacancy = new Map<string, { name: string; is_required: boolean }[]>();
  for (const vt of mockVacancyTechnology) {
    const name = techNameById.get(vt.technology_id);
    if (!name) continue;
    const list = byVacancy.get(vt.vacancy_id) ?? [];
    list.push({ name, is_required: vt.is_required });
    byVacancy.set(vt.vacancy_id, list);
  }
  return mockVacancies.map((v) => ({
    ...v,
    technologies: byVacancy.get(v.id) ?? [],
  }));
}
