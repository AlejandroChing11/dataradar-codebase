const companyById = new Map(mockCompanies.map((c) => [c.id, c]));

function yearsRaw(d: VacancyDraft): string | null {
  const min = d.years_min;
  const max = d.years_max;
  if (min === null && max === null) return null;
  if (min === null) return `Hasta ${max} años`;
  if (max === null) return `${min}+ años`;
  return min === max ? `${min} año` : `${min}–${max} años`;
}

const techNameById = new Map(mockTechnologies.map((t) => [t.id, t.name]));

function buildVacancies(): Vacancy[] {
  return drafts.map((d) => {
    const company = companyById.get(d.company_id);
    return {
      id: d.id,
      company_id: d.company_id,
      title: d.title,
      company_name: company?.name ?? null,
      location: d.location,
      work_mode: d.work_mode,
      remote_countries:
        d.work_mode === "remote_country" ? [d.location ?? ""] : null,
      remote_raw: d.remote_raw,
      years_raw: yearsRaw(d),
      years_min: d.years_min,
      years_max: d.years_max,
      language_req: d.language_req,
      block: d.block,
      url: d.url,
      alt_url: d.alt_url,
      fit_line: d.fit_line,
      source_portal: d.source_portal,
      salary_raw: d.salary_raw,
      published_date: daysAgo(d.first_seen_days_ago),
      first_seen: daysAgo(d.first_seen_days_ago),
      last_seen: daysAgo(d.last_seen_days_ago),
      times_seen: d.times_seen,
      is_repost: d.is_repost,
      is_active: d.is_active,
      created_at: daysAgo(d.first_seen_days_ago),
      updated_at: daysAgo(d.last_seen_days_ago),
      // Refleja la columna denormalizada `vacancies.stack` (jsonb) del DDL:
      // [{ tech, req }] con el nombre de tecnología resuelto desde el id.
      stack: d.stack.map(([technology_id, is_required]) => ({
        tech: techNameById.get(technology_id) ?? "",
        req: is_required,
      })),
    };
  });
}

